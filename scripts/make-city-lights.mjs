// Builds src/lib/data/city-lights.ts: world places with at least 5,000
// inhabitants (GeoNames, via the all-the-cities package, CC BY 4.0), packed
// as 5 bytes each for the night-lights Earth background.
// Run: node scripts/make-city-lights.mjs /path/to/all-the-cities/package
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

const dir = process.argv[2];
if (!dir) throw new Error('Pass the path of an unpacked all-the-cities package (npm pack all-the-cities).');
const cities = createRequire(import.meta.url)(path.resolve(dir, 'index.js'));
const MIN = 5000;
const list = cities.filter(c => c.population >= MIN).sort((a, b) => a.population - b.population);
// lon, lat as uint16 (≈ 0.0055° / 0.0027° steps), population as uint8 on a log scale from 5,000 to 50 million.
const buf = Buffer.alloc(list.length * 5);
list.forEach((c, i) => {
  const [lon, lat] = c.loc.coordinates;
  buf.writeUInt16LE(Math.round(((lon + 180) / 360) * 65535), i * 5);
  buf.writeUInt16LE(Math.round(((lat + 90) / 180) * 65535), i * 5 + 2);
  buf.writeUInt8(Math.max(0, Math.min(255, Math.round((Math.log10(c.population / MIN) / 4) * 255))), i * 5 + 4);
});
const out = `// Generated by scripts/make-city-lights.mjs — do not edit.
// ${list.length} places with ≥ ${MIN.toLocaleString('en')} inhabitants from GeoNames (geonames.org, CC BY 4.0).
// Each record: lon uint16, lat uint16, log-population uint8 (little-endian).
export const MIN_POPULATION = ${MIN};
export const CITY_COUNT = ${list.length};
export const CITY_DATA = '${buf.toString('base64')}';
`;
writeFileSync(new URL('../src/lib/data/city-lights.ts', import.meta.url), out);
console.log('wrote', list.length, 'places,', out.length, 'bytes');
